/* ===================================
   Image Modal
   =================================== */
let currentModalIndex = 0;
let visibleItems = [];

function updateVisibleItems() {
    visibleItems = Array.from(portfolioItems).filter(item => !item.classList.contains('hidden'));
}

function openModal(index) {
    updateVisibleItems();
    currentModalIndex = index;
    const item = visibleItems[index];
    const img = item.querySelector('img');
    
    modalImage.src = img.src;
    modalImage.alt = img.alt;
    modalCaption.textContent = img.alt;
    imageModal.classList.add('active');
    document.body.style.overflow = 'hidden';
}

function closeModal() {
    imageModal.classList.remove('active');
    document.body.style.overflow = '';
}

function nextImage() {
    updateVisibleItems();
    currentModalIndex = (currentModalIndex + 1) % visibleItems.length;
    const item = visibleItems[currentModalIndex];
    const img = item.querySelector('img');
    
    modalImage.src = img.src;
    modalImage.alt = img.alt;
    modalCaption.textContent = img.alt;
}

function prevImage() {
    updateVisibleItems();
    currentModalIndex = (currentModalIndex - 1 + visibleItems.length) % visibleItems.length;
    const item = visibleItems[currentModalIndex];
    const img = item.querySelector('img');
    
    modalImage.src = img.src;
    modalImage.alt = img.alt;
    modalCaption.textContent = img.alt;
}

portfolioItems.forEach((item, index) => {
    item.addEventListener('click', () => {
        updateVisibleItems();
        const visibleIndex = visibleItems.indexOf(item);
        openModal(visibleIndex);
    });
});

modalClose.addEventListener('click', closeModal);
modalNext.addEventListener('click', nextImage);
modalPrev.addEventListener('click', prevImage);

imageModal.addEventListener('click', (e) => {
    if (e.target === imageModal) {
        closeModal();
    }
});

document.addEventListener('keydown', (e) => {
    if (imageModal.classList.contains('active')) {
        if (e.key === 'Escape') closeModal();
        if (e.key === 'ArrowRight') nextImage();
        if (e.key === 'ArrowLeft') prevImage();
    }
});

